type docFixture struct {
	admin  *pgx.Conn
	pool   *pgxpool.Pool
	schema string
}

func newDocFixture(ctx context.Context, t *testing.T) *docFixture {
	admin := adminConn(ctx, t)
	stamp := time.Now().UnixNano()
	role := fmt.Sprintf("dt_role_%d", stamp)
	password := fmt.Sprintf("pw%d", stamp)
	schema := fmt.Sprintf("dt_%d", stamp)

	_, err := admin.Exec(ctx, fmt.Sprintf("CREATE ROLE %s LOGIN PASSWORD '%s'", role, password))
	must(t, err, "create role")
	t.Cleanup(func() {
		cctx, cancel := cleanupContext()
		defer cancel()
		_, _ = admin.Exec(cctx, fmt.Sprintf("DROP OWNED BY %s", role))
		_, _ = admin.Exec(cctx, fmt.Sprintf("DROP ROLE %s", role))
	})
	_, err = admin.Exec(ctx, fmt.Sprintf("CREATE SCHEMA %[1]s; GRANT USAGE ON SCHEMA %[1]s TO %[2]s", schema, role))
	must(t, err, "create schema")
	t.Cleanup(func() {
		cctx, cancel := cleanupContext()
		defer cancel()
		_, _ = admin.Exec(cctx, fmt.Sprintf("DROP SCHEMA %s CASCADE", schema))
	})

	config, err := pgxpool.ParseConfig(testDSN(t))
	must(t, err, "parse config")
	config.ConnConfig.User = role
	config.ConnConfig.Password = password
	config.MaxConns = 2
	pool, err := pgxpool.NewWithConfig(ctx, config)
	must(t, err, "pool")
	t.Cleanup(pool.Close)
	return &docFixture{admin: admin, pool: pool, schema: schema}
}

func (f *docFixture) exec(ctx context.Context, t *testing.T, format string, args ...any) {
	sql := fmt.Sprintf(format, args...)
	_, err := f.admin.Exec(ctx, sql+fmt.Sprintf(";GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA %s TO PUBLIC", f.schema))
	must(t, err, "setup")
}

func TestLoadDocTableReadsCompositeKeyGeneratedAndQuotedColumns(t *testing.T) {
	ctx := testContext(t)
	f := newDocFixture(ctx, t)
	f.exec(ctx, t, `CREATE TABLE %s.items (
		region text NOT NULL, "MixedCase" integer, id text NOT NULL, doc jsonb NOT NULL,
		stored integer GENERATED ALWAYS AS ("MixedCase" * 2) STORED,
		always_id bigint GENERATED ALWAYS AS IDENTITY,
		default_id bigint GENERATED BY DEFAULT AS IDENTITY,
		tags text[],
		UNIQUE ("MixedCase"),
		PRIMARY KEY (id, region))`, f.schema)

	got, err := loadDocTable(ctx, f.pool, f.schema+".items")

	require.NoError(t, err)
	assert.Equal(t, []docColumn{{"region", "text"}, {"MixedCase", "integer"}, {"default_id", "bigint"}, {"tags", "text[]"}}, got.Columns)
	assert.Equal(t, []string{"id", "region"}, got.PrimaryKey)
}

func TestLoadDocTableRejectsBadShapesNamingTheTable(t *testing.T) {
	ctx := testContext(t)
	f := newDocFixture(ctx, t)
	for name, tc := range map[string]struct {
		ddl  string
		want string
	}{
		"no id":          {"CREATE TABLE %s.%s (doc jsonb, k text PRIMARY KEY)", "id"},
		"id not text":    {"CREATE TABLE %s.%s (id integer PRIMARY KEY, doc jsonb)", "id"},
		"no doc":         {"CREATE TABLE %s.%s (id text PRIMARY KEY)", "doc"},
		"doc not jsonb":  {"CREATE TABLE %s.%s (id text PRIMARY KEY, doc json)", "doc"},
		"no primary key": {"CREATE TABLE %s.%s (id text, doc jsonb)", "primary key"},
		"key without id": {"CREATE TABLE %s.%s (id text, doc jsonb, k text PRIMARY KEY)", "primary key"},
		"doc generated":  {"CREATE TABLE %s.%s (id text PRIMARY KEY, doc jsonb GENERATED ALWAYS AS ('{}'::jsonb) STORED)", "generated"},
		"id generated":   {"CREATE TABLE %s.%s (id text GENERATED ALWAYS AS ('k') STORED PRIMARY KEY, doc jsonb)", "generated"},
	} {
		t.Run(name, func(t *testing.T) {
			table := fmt.Sprintf("bad_%d", time.Now().UnixNano())
			f.exec(ctx, t, tc.ddl, f.schema, table)

			_, err := loadDocTable(ctx, f.pool, f.schema+"."+table)

			require.Error(t, err)
			assert.Contains(t, err.Error(), table)
			assert.Contains(t, err.Error(), tc.want)
		})
	}
	t.Run("missing table", func(t *testing.T) {
		_, err := loadDocTable(ctx, f.pool, f.schema+".absent")

		require.Error(t, err)
		assert.Contains(t, err.Error(), "absent")
		assert.Contains(t, err.Error(), "does not exist")
	})
}

func TestGetTablePrimaryKeySchemaKeepsSameNamedConstraintsApart(t *testing.T) {
	ctx := testContext(t)
	f := newDocFixture(ctx, t)
	other := f.schema + "_other"
	_, err := f.admin.Exec(ctx, fmt.Sprintf("CREATE SCHEMA %[1]s; GRANT USAGE ON SCHEMA %[1]s TO PUBLIC", other))
	must(t, err, "other schema")
	t.Cleanup(func() {
		cctx, cancel := cleanupContext()
		defer cancel()
		_, _ = f.admin.Exec(cctx, fmt.Sprintf("DROP SCHEMA %s CASCADE", other))
	})
	f.exec(ctx, t, "CREATE TABLE %s.t (a int, b int, CONSTRAINT shared_pk PRIMARY KEY (a))", f.schema)
	_, err = f.admin.Exec(ctx, fmt.Sprintf("CREATE TABLE %s.t (b int, c int, CONSTRAINT shared_pk PRIMARY KEY (c, b)); CREATE TABLE %[1]s.u (z int, CONSTRAINT shared_pk_u PRIMARY KEY (z)); GRANT ALL ON ALL TABLES IN SCHEMA %[1]s TO PUBLIC", other))
	must(t, err, "other tables")

	got, err := getTablePrimaryKeySchema(ctx, f.pool)

	require.NoError(t, err)
	assert.Equal(t, []string{"a"}, got[f.schema+".t"])
	assert.Equal(t, []string{"c", "b"}, got[other+".t"])
	assert.Equal(t, []string{"z"}, got[other+".u"])
}

